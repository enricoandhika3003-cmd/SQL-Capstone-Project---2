-- CUSTOMER QUERYS
SELECT *
FROM CUSTOMERS
WHERE CUSTOMER_NAME LIKE 'A%';

SELECT *
FROM CUSTOMERS
WHERE CUSTOMER_NAME LIKE '%OR%';

SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    P.PRODUCT_NAME,
    P.PRODUCT_CATEGORY,
    P.UNIT_PRICE,
    E.EXPORT_COUNTRY,
    E.EXPORT_DATE,
    E.QUANTITY
FROM EXPORTS E
JOIN CUSTOMERS C
    ON E.CUSTOMER_ID = C.CUSTOMER_ID
JOIN PRODUCTS P
    ON E.PRODUCT_ID = P.PRODUCT_ID
ORDER BY C.CUSTOMER_NAME;

SELECT
    C.CUSTOMER_NAME,
    P.PRODUCT_NAME,
    E.EXPORT_COUNTRY,
    E.QUANTITY,
    E.EXPORT_DATE
FROM CUSTOMERS C
JOIN EXPORTS E
    ON C.CUSTOMER_ID = E.CUSTOMER_ID
JOIN PRODUCTS P
    ON E.PRODUCT_ID = P.PRODUCT_ID
WHERE C.CUSTOMER_NAME LIKE 'A%'
   AND C.CUSTOMER_NAME LIKE '%OR%'
ORDER BY C.CUSTOMER_NAME;